const slugify = (value) => value.toLowerCase().replace(/[.']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')

// "team/slug" -> portrait file, preferring WebP, then PNG, then JPG when several exist.
const formatOrder = ['webp', 'png', 'jpg', 'jpeg']
const portraitFiles = {}
portraits
  .slice()
  .sort((a, b) => formatOrder.indexOf(a.split('.').pop().toLowerCase()) - formatOrder.indexOf(b.split('.').pop().toLowerCase()))
  .forEach((file) => {
    const key = file.replace(/\.[^.]+$/, '')
    portraitFiles[key] ??= file
  })

const allPlayers = Object.entries(roster).flatMap(([schoolId, names]) =>
  names.map((name, index) => ({
    id: `${schoolId}-${slugify(name)}`,
    name,
    nameJa: japaneseNames[name],
    affiliation: affiliations[name] ? { en: affiliations[name][0], ja: affiliations[name][1] } : null,
    schoolId,
    seed: index,
    image: portraitFiles[`${schoolId}/${slugify(name)}`] ? `${import.meta.env.BASE_URL}players/${portraitFiles[`${schoolId}/${slugify(name)}`]}` : null,
    focus: faceFocus[`${schoolId}/${slugify(name)}`] ?? [50, 30],
  })),
)

// Characters without a portrait yet stay in the roster above but are hidden from the site, as are
// teams left with nobody to show. They appear automatically once their photo is added.
export const players = allPlayers.filter((player) => player.image)
export const schools = allSchools.filter((school) => players.some((player) => player.schoolId === school.id))

export const schoolMap = Object.fromEntries(schools.map((school) => [school.id, school]))
